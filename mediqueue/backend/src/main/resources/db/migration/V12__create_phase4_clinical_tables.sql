-- V12: Create Phase 4 Clinical Health Records Tables

CREATE TABLE consultation_records (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    consultation_reference VARCHAR(64) NOT NULL UNIQUE,
    appointment_id BIGINT NOT NULL UNIQUE,
    patient_id BIGINT NOT NULL,
    doctor_id BIGINT NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'SCHEDULED',
    actual_start_timestamp TIMESTAMP(6) NULL,
    actual_end_timestamp TIMESTAMP(6) NULL,
    cancellation_reason VARCHAR(255) NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    CONSTRAINT fk_cr_appointment FOREIGN KEY (appointment_id) REFERENCES appointments (id) ON DELETE CASCADE,
    CONSTRAINT fk_cr_patient FOREIGN KEY (patient_id) REFERENCES patients (id) ON DELETE CASCADE,
    CONSTRAINT fk_cr_doctor FOREIGN KEY (doctor_id) REFERENCES doctors (id) ON DELETE CASCADE,
    INDEX idx_cr_patient_status (patient_id, status),
    INDEX idx_cr_doctor_status (doctor_id, status),
    INDEX idx_cr_start_time (actual_start_timestamp)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE visit_summaries (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    summary_reference VARCHAR(64) NOT NULL UNIQUE,
    consultation_id BIGINT NOT NULL,
    appointment_id BIGINT NOT NULL,
    patient_id BIGINT NOT NULL,
    authoring_doctor_id BIGINT NOT NULL,
    chief_complaint VARCHAR(500) NULL,
    diagnosis TEXT NULL,
    clinical_notes TEXT NULL,
    treatment_plan TEXT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'DRAFT',
    approved_at TIMESTAMP(6) NULL,
    approved_by_doctor_id BIGINT NULL,
    version_number INT NOT NULL DEFAULT 1,
    revision_reason VARCHAR(255) NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    CONSTRAINT fk_vs_consultation FOREIGN KEY (consultation_id) REFERENCES consultation_records (id) ON DELETE CASCADE,
    CONSTRAINT fk_vs_appointment FOREIGN KEY (appointment_id) REFERENCES appointments (id) ON DELETE CASCADE,
    CONSTRAINT fk_vs_patient FOREIGN KEY (patient_id) REFERENCES patients (id) ON DELETE CASCADE,
    CONSTRAINT fk_vs_authoring_doc FOREIGN KEY (authoring_doctor_id) REFERENCES doctors (id) ON DELETE CASCADE,
    CONSTRAINT fk_vs_approved_doc FOREIGN KEY (approved_by_doctor_id) REFERENCES doctors (id) ON DELETE SET NULL,
    INDEX idx_vs_patient_status (patient_id, status),
    INDEX idx_vs_consultation (consultation_id),
    INDEX idx_vs_author (authoring_doctor_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE visit_summary_revisions (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    visit_summary_id BIGINT NOT NULL,
    revision_number INT NOT NULL,
    chief_complaint VARCHAR(500) NULL,
    diagnosis TEXT NULL,
    clinical_notes TEXT NULL,
    treatment_plan TEXT NULL,
    archived_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    archived_by_doctor_id BIGINT NOT NULL,
    revision_reason VARCHAR(255) NULL,
    CONSTRAINT fk_vsr_summary FOREIGN KEY (visit_summary_id) REFERENCES visit_summaries (id) ON DELETE CASCADE,
    CONSTRAINT fk_vsr_doctor FOREIGN KEY (archived_by_doctor_id) REFERENCES doctors (id) ON DELETE CASCADE,
    INDEX idx_vsr_summary (visit_summary_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE prescriptions (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    prescription_reference VARCHAR(64) NOT NULL UNIQUE,
    consultation_id BIGINT NOT NULL,
    appointment_id BIGINT NOT NULL,
    patient_id BIGINT NOT NULL,
    doctor_id BIGINT NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'ISSUED',
    issued_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    cancelled_at TIMESTAMP(6) NULL,
    cancellation_reason VARCHAR(255) NULL,
    notes VARCHAR(500) NULL,
    version_number INT NOT NULL DEFAULT 1,
    parent_prescription_id BIGINT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    CONSTRAINT fk_rx_consultation FOREIGN KEY (consultation_id) REFERENCES consultation_records (id) ON DELETE CASCADE,
    CONSTRAINT fk_rx_appointment FOREIGN KEY (appointment_id) REFERENCES appointments (id) ON DELETE CASCADE,
    CONSTRAINT fk_rx_patient FOREIGN KEY (patient_id) REFERENCES patients (id) ON DELETE CASCADE,
    CONSTRAINT fk_rx_doctor FOREIGN KEY (doctor_id) REFERENCES doctors (id) ON DELETE CASCADE,
    INDEX idx_rx_patient_status (patient_id, status),
    INDEX idx_rx_consultation (consultation_id),
    INDEX idx_rx_doctor (doctor_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE prescription_items (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    prescription_id BIGINT NOT NULL,
    medication_name VARCHAR(200) NOT NULL,
    dosage VARCHAR(100) NOT NULL,
    frequency VARCHAR(100) NOT NULL,
    duration_days INT NOT NULL,
    route VARCHAR(50) NULL,
    instructions VARCHAR(500) NULL,
    item_order INT NOT NULL DEFAULT 0,
    CONSTRAINT fk_rxi_prescription FOREIGN KEY (prescription_id) REFERENCES prescriptions (id) ON DELETE CASCADE,
    INDEX idx_rxi_prescription (prescription_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE follow_ups (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    follow_up_reference VARCHAR(64) NOT NULL UNIQUE,
    consultation_id BIGINT NOT NULL,
    appointment_id BIGINT NOT NULL,
    patient_id BIGINT NOT NULL,
    doctor_id BIGINT NOT NULL,
    recommended_date DATE NOT NULL,
    instructions VARCHAR(500) NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'SCHEDULED',
    reminder_status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    reminder_sent_at TIMESTAMP(6) NULL,
    completed_at TIMESTAMP(6) NULL,
    cancellation_reason VARCHAR(255) NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    CONSTRAINT fk_fu_consultation FOREIGN KEY (consultation_id) REFERENCES consultation_records (id) ON DELETE CASCADE,
    CONSTRAINT fk_fu_appointment FOREIGN KEY (appointment_id) REFERENCES appointments (id) ON DELETE CASCADE,
    CONSTRAINT fk_fu_patient FOREIGN KEY (patient_id) REFERENCES patients (id) ON DELETE CASCADE,
    CONSTRAINT fk_fu_doctor FOREIGN KEY (doctor_id) REFERENCES doctors (id) ON DELETE CASCADE,
    INDEX idx_fu_patient_status (patient_id, status),
    INDEX idx_fu_doctor_date (doctor_id, recommended_date),
    INDEX idx_fu_reminder (reminder_status, recommended_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE medical_documents (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    document_reference VARCHAR(64) NOT NULL UNIQUE,
    patient_id BIGINT NOT NULL,
    appointment_id BIGINT NULL,
    consultation_id BIGINT NULL,
    uploaded_by_user_id BIGINT NOT NULL,
    document_category VARCHAR(50) NOT NULL,
    original_file_name VARCHAR(255) NOT NULL,
    storage_key VARCHAR(128) NOT NULL UNIQUE,
    content_type VARCHAR(100) NOT NULL,
    file_size_bytes BIGINT NOT NULL,
    checksum_sha256 VARCHAR(64) NOT NULL,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    CONSTRAINT fk_md_patient FOREIGN KEY (patient_id) REFERENCES patients (id) ON DELETE CASCADE,
    CONSTRAINT fk_md_appointment FOREIGN KEY (appointment_id) REFERENCES appointments (id) ON DELETE SET NULL,
    CONSTRAINT fk_md_consultation FOREIGN KEY (consultation_id) REFERENCES consultation_records (id) ON DELETE SET NULL,
    CONSTRAINT fk_md_user FOREIGN KEY (uploaded_by_user_id) REFERENCES users (id) ON DELETE CASCADE,
    INDEX idx_md_patient_deleted (patient_id, is_deleted),
    INDEX idx_md_consultation (consultation_id),
    INDEX idx_md_user (uploaded_by_user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE clinical_audit_events (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    actor_user_id BIGINT NULL,
    actor_role VARCHAR(50) NULL,
    action VARCHAR(100) NOT NULL,
    resource_type VARCHAR(50) NOT NULL,
    resource_id BIGINT NULL,
    patient_id BIGINT NULL,
    outcome VARCHAR(30) NOT NULL,
    safe_reason VARCHAR(255) NULL,
    event_timestamp TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    INDEX idx_cae_patient_time (patient_id, event_timestamp),
    INDEX idx_cae_resource (resource_type, resource_id),
    INDEX idx_cae_actor_time (actor_user_id, event_timestamp)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
